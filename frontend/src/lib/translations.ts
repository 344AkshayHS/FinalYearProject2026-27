export function districtName(key: string, language: Language) {
  return DISTRICT_NAMES[key]?.[language] ?? key;
}

// Taluk names come from the Agriculture Census in capitals ("K.R. PET", "AFZALPUR + ALAND"). In Kannada, from
// taluk-names.ts; the English name is written in normal letters ("K.R. Pet").
export function talukName(name: string, language: Language = 'en') {
  if (language === 'kn' && TALUK_NAMES_KN[name]) {
    return TALUK_NAMES_KN[name];
  }
  return name.toLowerCase().replace(/(^|[\s.(])([a-z])/g, (_, before, letter) => before + letter.toUpperCase());
}

